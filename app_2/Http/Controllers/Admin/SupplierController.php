        $suppliers->s_phone= $request ->input('s_phone');

        if($request ->input('s_email')){
            $suppliers->s_email= $request ->input('s_email');
        }
            
        if($request ->input('s_password')){
            $suppliers->s_password= Hash::make($request ->input('s_password'));
        }

        if($request ->input('type')){
            $suppliers->type= $request ->input('type');
        }else{
            $suppliers->type= $oldType;
        }

        if ($request->hasFile('image')) {
            $image = $request->file('image');

            File::delete(public_path('uploads/supplier-profile/'.$suppliers->image));

            $croppedImage = Image::make($image)->fit(500, 500);

            $filename = time() . '.' . $image->getClientOriginalExtension();

            $croppedImage->save(public_path('uploads/supplier-profile/' . $filename));

            $suppliers->image= str_replace('public/uploads/supplier-profile/','',$filename);
        }

        //update user
        $users= User::where('email','=',$oldMail)->first();

        
        $users->name= $request ->input('s_first_name');
        $users->phone = $request ->input('s_phone');
        $users->image = $suppliers->image;

        if($request ->input('type')){
            $users->type= $request ->input('type');
        }else{
            $users->type= $oldType;
        }

        if($request ->input('s_email')){
            $users->email = $request ->input('s_email');
        }
        if($request ->input('s_password')){
            $users->password= Hash::make($request ->input('s_password'));
        }
        
        $users->update();

        $suppliers->update();

        

        if(auth()->user()->type == 'Admin'){
            Session::flash('success', 'Supplier has been Updated Successfully');
        return Redirect::route('supplier.index');
        }else{
            Session::flash('success', 'Supplier has been Updated Successfully');
            return Redirect::route('supplier.edit',$suppliers);
        }
    }

